import { allowedHashes, assertKeyAlgorithm, generateParams, hashFor, signParams } from './algorithms'
import { copy, wipe } from './bytes'
import type { KeyvaultConfig } from './config'
import { open, rewrap, seal } from './envelope'
import { KeyvaultError } from './errors'
import { algorithmOf, keyFamily, publicKeyFromPkcs8, webCryptoImportParams } from './pkcs8'
import type { EncryptedKeyRecord, GeneratedKey, HashAlgorithm, KeyAlgorithm, KeyProvider, Signer, SignerOptions } from './types'

/**
 * Keys encrypted with the configured master key and stored by the caller (a database row).
 * Signing runs on WebCrypto: each call decrypts the PKCS#8, imports it as a non-extractable
 * CryptoKey, signs, and wipes the decrypted bytes before returning.
 */
export class LocalKeyProvider implements KeyProvider {
  readonly #config: KeyvaultConfig

  constructor(config: KeyvaultConfig) {
    this.#config = config
  }

  async generate(algorithm: KeyAlgorithm, binding: string): Promise<GeneratedKey> {
    assertKeyAlgorithm(algorithm)
    // Extractable only so the PKCS#8 can be encrypted; the CryptoKey is dropped right after.
    const pair = (await crypto.subtle.generateKey(generateParams(algorithm), true, ['sign', 'verify'])) as CryptoKeyPair
    const pkcs8 = new Uint8Array(await crypto.subtle.exportKey('pkcs8', pair.privateKey))
    try {
      const public_key_spki = new Uint8Array(await crypto.subtle.exportKey('spki', pair.publicKey))
      const record = await seal(this.#config, pkcs8, binding)
      return { record, algorithm, public_key_spki }
    } finally {
      wipe(pkcs8)
    }
  }

  async sign(record: EncryptedKeyRecord, binding: string, data: Uint8Array, hash: HashAlgorithm): Promise<Uint8Array<ArrayBuffer>> {
    return this.#sign(record, binding, data, hash, null)
  }

  async publicKey(record: EncryptedKeyRecord, binding: string): Promise<Uint8Array<ArrayBuffer>> {
    const pkcs8 = await open(this.#config, record, binding)
    try {
      return (await publicKeyFromPkcs8(pkcs8)).spki
    } finally {
      wipe(pkcs8)
    }
  }

  signer(record: EncryptedKeyRecord, binding: string, algorithm: KeyAlgorithm, options: SignerOptions = {}): Signer {
    assertKeyAlgorithm(algorithm)
    const hash = options.hash ?? hashFor(algorithm)
    if (!allowedHashes(algorithm).includes(hash)) throw new KeyvaultError('unsupported_algorithm', `${algorithm} keys cannot sign with ${hash}`)
    const sign = (data: Uint8Array) => this.#sign(record, binding, data, hash, algorithm)
    return Object.freeze({ key_algorithm: algorithm, hash, sign })
  }

  /**
   * Stores an existing PKCS#8 key. Used for an administrator's SSH CA key import (a step-up
   * action) and for test fixtures; every other key is generated by `generate`.
   */
  async importPkcs8(pkcs8: Uint8Array, binding: string): Promise<GeneratedKey> {
    const own = copy(pkcs8)
    try {
      const { spki, algorithm } = await publicKeyFromPkcs8(own)
      // Import once to make sure WebCrypto accepts the key before it is stored. It also refuses
      // keys whose public half does not belong to the secret half.
      await crypto.subtle
        .importKey('pkcs8', own, webCryptoImportParams(keyFamily(own), hashFor(algorithm)), false, ['sign'])
        .catch(() => {
          throw new KeyvaultError('key_mismatch', 'The private key is not valid or does not match its public key')
        })
      // A key file whose public half does not belong to its secret half would later sign
      // certificates nobody can verify: prove the pair with one signature before storing it.
      await this.#checkPair(own, spki, algorithm)
      const record = await seal(this.#config, own, binding)
      return { record, algorithm, public_key_spki: spki }
    } finally {
      wipe(own)
    }
  }

  async #checkPair(pkcs8: Uint8Array, spki: Uint8Array, algorithm: KeyAlgorithm): Promise<void> {
    const hash = hashFor(algorithm)
    const family = keyFamily(pkcs8)
    const privateKey = await crypto.subtle.importKey('pkcs8', copy(pkcs8), webCryptoImportParams(family, hash), false, ['sign'])
    const verifyParams = family.kind === 'ec' ? { name: 'ECDSA', namedCurve: family.curve } : family.kind === 'ed25519' ? { name: 'Ed25519' } : { name: 'RSASSA-PKCS1-v1_5', hash }
    const publicKey = await crypto.subtle.importKey('spki', copy(spki), verifyParams, false, ['verify'])
    const probe = crypto.getRandomValues(new Uint8Array(32))
    const signature = await crypto.subtle.sign(signParams(algorithm), privateKey, probe)
    if (!(await crypto.subtle.verify(signParams(algorithm), publicKey, signature, probe))) {
      throw new KeyvaultError('key_mismatch', 'The private key does not match its public key')
    }
  }

  /** Re-wraps the record's DEK under the current master key; the key ciphertext stays as is. */
  rewrap(record: EncryptedKeyRecord, binding: string): Promise<EncryptedKeyRecord> {
    return rewrap(this.#config, record, binding)
  }

  /** True when the record was wrapped with a previous master key. */
  needsRewrap(record: EncryptedKeyRecord): boolean {
    return record.kek_id !== this.#config.current_kek_id
  }

  async #sign(record: EncryptedKeyRecord, binding: string, data: Uint8Array, hash: HashAlgorithm, expected: KeyAlgorithm | null): Promise<Uint8Array<ArrayBuffer>> {
    if (!(data instanceof Uint8Array)) throw new TypeError('data must be a Uint8Array')
    const pkcs8 = await open(this.#config, record, binding)
    try {
      const family = keyFamily(pkcs8)
      const key = await crypto.subtle.importKey('pkcs8', pkcs8, webCryptoImportParams(family, hash), false, ['sign'])
      const algorithm = algorithmOf(family, key.algorithm)
      if (expected && algorithm !== expected) {
        throw new KeyvaultError('key_mismatch', 'The stored key does not match the expected algorithm')
      }
      if (!allowedHashes(algorithm).includes(hash)) {
        throw new KeyvaultError('unsupported_algorithm', `${algorithm} keys sign with ${hashFor(algorithm)}`)
      }
      return new Uint8Array(await crypto.subtle.sign(signParams(algorithm), key, copy(data)))
    } finally {
      wipe(pkcs8)
    }
  }
}
